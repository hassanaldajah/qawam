"""Rebuild the Qawam mark as crisp vector clip paths over the original artwork.

Input : brand/source/symbol-crop.png (owner's logo).
Output: public/brand/qawam-mark.webp (edge-cleaned art, 2x)
        src/brand/markPaths.ts      (base / front leg / back leg clip paths)
The legs are separate layers so the UI can animate only them.
Run:  anaconda3/python.exe scripts/build-mark.py   (needs numpy, scipy, scikit-image, pillow)
"""
import numpy as np
from PIL import Image
from scipy import ndimage
from skimage import measure

SRC = "brand/source/symbol-crop.png"
UP = 4                      # contour supersampling
T = 85                      # edge threshold (distance from background colour)
CUT_FRONT, CUT_BASE = 236, 243   # front leg starts at y>=236; torso keeps y<243 (overlap = seamless hip)

im = np.asarray(Image.open(SRC).convert("RGB")).astype(float)
H, W, _ = im.shape
bg = np.median(np.concatenate([im[:6].reshape(-1, 3), im[-6:].reshape(-1, 3)]), axis=0)
dist = np.sqrt(((im - bg) ** 2).sum(-1))
lab = measure.label(dist > 60, connectivity=1)
props = sorted(measure.regionprops(lab), key=lambda p: -p.area)
props = [p for p in props if p.area > 200]
body = props[0].label                                   # torso + front leg (largest)
back = next(p.label for p in props if p.bbox[1] < 100 and p.bbox[2] > 470)  # long sweep to the bottom-left

def field(sel):
    """Supersampled distance field restricted to selected pixels -> smooth contours."""
    f = np.where(sel, dist, 0.0)
    return ndimage.zoom(f, UP, order=3)

yy = np.arange(H)[:, None] * np.ones((1, W))
front_sel = (lab == body) & (yy >= CUT_FRONT)
back_sel = lab == back
base_sel = (lab > 0) & (lab != back) & ~((lab == body) & (yy >= CUT_BASE))
# keep tiny specks out
base_sel &= np.isin(lab, [p.label for p in props])

def to_path(sel, tol=0.12):
    f = np.pad(field(sel), 2)
    parts = []
    for c in measure.find_contours(f, T):
        if len(c) < 12: continue
        c = measure.approximate_polygon(c, tolerance=tol * UP)
        pts = [((x - 2 + 0.5) / UP - 0.5, (y - 2 + 0.5) / UP - 0.5) for y, x in c]
        parts.append("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + "Z")
    return "".join(parts)

paths = {"base": to_path(base_sel), "front": to_path(front_sel), "back": to_path(back_sel)}

# Edge-clean art: every pixel takes the colour of the nearest solid interior pixel,
# so the vector clip never shows a dark anti-aliased fringe.
art = im.copy()
for p in props:                                   # per component: no colour bleed between shapes
    m = lab == p.label
    inner = ndimage.binary_erosion(m, iterations=3)
    if not inner.any(): continue
    _, (iy, ix) = ndimage.distance_transform_edt(~inner, return_indices=True)
    edge = m & ~inner
    art[edge] = im[iy[edge], ix[edge]]
fg = np.isin(lab, [p.label for p in props])      # background takes the nearest shape colour (no dark halo when upscaled)
_, (iy, ix) = ndimage.distance_transform_edt(~fg, return_indices=True)
art = art[iy, ix].astype(np.uint8)
Image.fromarray(art).resize((W * 2, H * 2), Image.LANCZOS).save("public/brand/qawam-mark.webp", quality=90, method=6)

with open("src/brand/markPaths.ts", "w", encoding="utf-8") as fh:
    fh.write("// Generated by scripts/build-mark.py from brand/source/symbol-crop.png. Do not edit.\n")
    fh.write(f"export const MARK_W = {W};\nexport const MARK_H = {H};\n")
    for k, v in paths.items():
        fh.write(f'export const {k.upper()}_D = "{v}";\n')

# Static mark (splash, favicon, OG): same clip paths, art embedded so it works as <img>.
import base64, io
buf = io.BytesIO(); Image.fromarray(art).save(buf, "WEBP", quality=86, method=6)
uri = "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()
allp = paths["base"] + paths["front"] + paths["back"]
with open("public/logo-mark.svg", "w", encoding="utf-8") as fh:
    fh.write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" role="img" aria-label="Qawam">'
             f'<clipPath id="c"><path d="{allp}" clip-rule="evenodd"/></clipPath>'
             f'<image href="{uri}" width="{W}" height="{H}" clip-path="url(#c)"/></svg>')

# App icons from the original artwork (anti-aliased mask, no posterised trace).
SS = 4
alpha = (ndimage.zoom(np.where(np.isin(lab, [p.label for p in props]), dist, 0.0), SS, order=3) > T)
rgba = Image.fromarray(art).resize((W * SS, H * SS), Image.BICUBIC).convert("RGBA")
rgba.putalpha(Image.fromarray((alpha * 255).astype(np.uint8)))
NAVY = (16, 23, 41, 255)
def icon(n, frac, name, bg=NAVY):
    c = Image.new("RGBA", (n, n), bg)
    w = int(n * frac); h = int(w * H / W)
    m = rgba.resize((w, h), Image.LANCZOS)
    c.alpha_composite(m, ((n - w) // 2, (n - h) // 2))
    c.convert("RGB" if bg[3] == 255 else "RGBA").save(f"public/icons/{name}.png", optimize=True)
for n, nm in [(192, "icon-192"), (512, "icon-512"), (180, "apple-touch-icon"), (32, "favicon-32"), (16, "favicon-16")]:
    icon(n, 0.8 if n > 32 else 0.96, nm)
for n in (192, 512):
    icon(n, 0.58, f"maskable-{n}")
og = Image.new("RGBA", (1200, 630), NAVY); m = rgba.resize((560, int(560 * H / W)), Image.LANCZOS)
og.alpha_composite(m, (320, (630 - m.height) // 2)); og.convert("RGB").save("public/og.png", optimize=True)
print({k: len(v) for k, v in paths.items()})
